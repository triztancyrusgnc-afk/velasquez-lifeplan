                <span class="sn-stepnum">01</span>
                <h4 style="margin-bottom:8px;">Stage 1: Denial</h4>
                <p style="margin:8px 0 0;color:var(--text-strong);opacity:0.82;font-size:0.9375rem;">Denial helps us survive the initial shock. It numbs the intensity of the moment and gives us time to slowly process the reality of the loss. You may feel like this cannot be happening or that there has been a mistake.</p>
            </div>

            <div class="sn-card fade-in">
                <span class="sn-stepnum">02</span>
                <h4 style="margin-bottom:8px;">Stage 2: Anger</h4>
                <p style="margin:8px 0 0;color:var(--text-strong);opacity:0.82;font-size:0.9375rem;">Anger may be directed at the deceased, yourself, God, or the world around you. It is a natural response to feeling powerless and hurt. Allow yourself to express anger safely without letting it consume you.</p>
            </div>

            <div class="sn-card fade-in">
                <span class="sn-stepnum">03</span>
                <h4 style="margin-bottom:8px;">Stage 3: Bargaining</h4>
                <p style="margin:8px 0 0;color:var(--text-strong);opacity:0.82;font-size:0.9375rem;">You may find yourself thinking "what if" or "if only" statements. Bargaining is the mind's way of trying to regain control or undo what has happened. Guilt often accompanies this stage as you replay events.</p>
            </div>

            <div class="sn-card fade-in">
                <span class="sn-stepnum">04</span>
                <h4 style="margin-bottom:8px;">Stage 4: Depression</h4>
                <p style="margin:8px 0 0;color:var(--text-strong);opacity:0.82;font-size:0.9375rem;">Deep sadness sets in as you begin to understand the certainty and gravity of the loss. This is not a sign of weakness — it is a appropriate response to a great loss. Be gentle with yourself during this time.</p>
            </div>

            <div class="sn-card fade-in">
                <span class="sn-stepnum">05</span>
                <h4 style="margin-bottom:8px;">Stage 5: Acceptance</h4>
                <p style="margin:8px 0 0;color:var(--text-strong);opacity:0.82;font-size:0.9375rem;">Acceptance does not mean you are "okay" with the loss. It means you acknowledge the reality of what has happened and are learning to live with it. Over time, you find new ways to connect with the memory of your loved one while moving forward with your life.</p>
            </div>
        </div>
